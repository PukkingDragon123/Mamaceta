const recent = {};
export function line(who, kind) {
  const arr = LINES[who]?.[kind];
  if (!arr || !arr.length) return null;
  const key = who + kind;
  let i = Math.floor(Math.random() * arr.length);
  if (arr.length > 1 && i === recent[key]) i = (i + 1) % arr.length;
  recent[key] = i;
  return arr[i];
}

